func TestRenderZshAndBash(t *testing.T) {
	cfg := testCfg()
	cfg.Shortcuts["dc"] = config.Shortcut{Environment: "dev", Action: "console"}
	cfg.Shortcuts["sb"] = config.Shortcut{Environment: "staging", Action: "shell"}
	cfg.Shortcuts["dl"] = config.Shortcut{Environment: "dev", Action: "logs"}
	zsh, err := Render(cfg, "zsh")
	if err != nil {
		t.Fatal(err)
	}
	bash, err := Render(cfg, "bash")
	if err != nil {
		t.Fatal(err)
	}
	if zsh != bash {
		t.Fatal("zsh and bash output should match")
	}
	again, _ := Render(cfg, "zsh")
	if again != zsh {
		t.Fatal("generation must be deterministic")
	}
	for _, want := range []string{
		"# Generated by kpod.",
		"k-dc() {",
		"command kpod 'dev' 'console' \"$@\"",
		"k-sb() {",
		"command kpod 'staging' 'shell' \"$@\"",
		"k-dl() {",
		"command kpod 'dev' 'logs' \"$@\"",
	} {
		if !strings.Contains(zsh, want) {
			t.Fatalf("missing %q in\n%s", want, zsh)
		}
	}
	if strings.Index(zsh, "k-dc") > strings.Index(zsh, "k-dl") {
		t.Fatal("expected sorted ids")
	}
}

func TestRenderCanonicalizesBashAlias(t *testing.T) {
	cfg := testCfg()
	cfg.Shortcuts["db"] = config.Shortcut{Environment: "dev", Action: "bash"}
	out, err := Render(cfg, "zsh")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, "command kpod 'dev' 'shell'") {
		t.Fatalf("%s", out)
	}
	if strings.Contains(out, " bash ") {
		t.Fatal(out)
	}
}

func TestRenderQuotesEnvironment(t *testing.T) {
	cfg := testCfg()
	cfg.Shortcuts["x"] = config.Shortcut{Environment: "dev;rm", Action: "console"}
	out, err := Render(cfg, "zsh")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(out, "kpod dev;rm") {
		t.Fatal("unquoted interpolation")
	}
	if !strings.Contains(out, "command kpod 'dev;rm' 'console'") {
		t.Fatalf("%s", out)
	}
}

func TestWriteAliasFiles(t *testing.T) {
	dir := t.TempDir()
	paths := config.NewPaths(dir)
	cfg := testCfg()
	cfg.Shortcuts["sc"] = config.Shortcut{Environment: "staging", Action: "console"}
	if err := WriteAliasFiles(paths, cfg); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(paths.AliasFile("zsh"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(body), "k-sc()") {
		t.Fatal(string(body))
	}
	if _, err := os.Stat(filepath.Join(dir, "shell", "aliases.bash")); err != nil {
		t.Fatal(err)
	}
}


func TestEnvPrefixCollision(t *testing.T) {
	cfg := config.Default()
	cfg.Contexts["c"] = config.Context{Environments: map[string]config.Environment{
		"production": {Namespace: "p"},
		"preview":    {Namespace: "v"},
	}}
	p := EnvPrefix("production", cfg.Aliases())
	v := EnvPrefix("preview", cfg.Aliases())
	if p == v {
		t.Fatalf("both became %s", p)
	}
}

func TestRecommendSmallSet(t *testing.T) {
	cfg := testCfg()
	cands := Recommend(cfg)
	on := 0
	for _, c := range cands {
		if c.DefaultOn {
			on++
		}
		if c.Action == "delete" || c.Action == "restart" {
			t.Fatal("must not recommend destructive")
		}
	}
	if on != 4 {
		t.Fatalf("default on count %d (console+shell × 2 envs)", on)
	}
}
